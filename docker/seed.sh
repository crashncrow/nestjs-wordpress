#!/usr/bin/env bash
# Seeds the local WordPress with deterministic demo content. Safe to run repeatedly:
# every step checks for existing data first (lookups by slug / name).
#
# The WP-CLI commands (docker/seed-wp.sh) run inside ONE short-lived `wpcli` container,
# which is much faster than one `docker compose run` per command. The host side only
# collects the generated application password and writes apps/demo/.env.
set -euo pipefail

# `/bin/pwd -P` resolves the on-disk path spelling (see docker/compose.sh).
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && /bin/pwd -P)"
COMPOSE=("$ROOT_DIR/docker/compose.sh")
ENV_FILE="$ROOT_DIR/apps/demo/.env"
WP_URL="${WP_URL:-http://localhost:8080}"
WEBHOOK_SECRET="${NWP_WEBHOOK_SECRET:-dev-webhook-secret-change-me}"
REVALIDATE_SECRET="${WEB_REVALIDATE_SECRET:-dev-revalidate-secret-change-me}"
WEB_ENV_FILE="$ROOT_DIR/apps/web/.env.local"

echo "→ Seeding WordPress at $WP_URL"

# The inner script is a separate file (not a heredoc inside $(...)) because the
# bash 3.2 shipped with macOS mis-parses `case` patterns in that construct.
OUTPUT="$("${COMPOSE[@]}" --profile seed run --rm -T -e WP_URL="$WP_URL" wpcli sh -s \
  < "$ROOT_DIR/docker/seed-wp.sh")"

APP_PASSWORD="$(printf '%s\n' "$OUTPUT" | sed -n 's/^APP_PASSWORD=//p' | tail -n1)"
if [ -z "$APP_PASSWORD" ]; then
  echo "✗ Could not read the application password. WP-CLI output:" >&2
  printf '%s\n' "$OUTPUT" >&2
  exit 1
fi

cat > "$ENV_FILE" <<EOF
# Generated by docker/seed.sh — do not commit.
PORT=3000
WP_URL=$WP_URL
WP_USERNAME=admin
WP_APP_PASSWORD=$APP_PASSWORD
WP_WEBHOOK_SECRET=$WEBHOOK_SECRET
REDIS_URL=redis://localhost:6379
WEB_REVALIDATE_URL=http://localhost:3001/api/revalidate/
WEB_REVALIDATE_SECRET=$REVALIDATE_SECRET
EOF

cat > "$WEB_ENV_FILE" <<EOF
# Generated by docker/seed.sh — do not commit.
API_URL=http://localhost:3000
REVALIDATE_SECRET=$REVALIDATE_SECRET
EOF

echo "✓ Seed complete. Credentials written to apps/demo/.env and apps/web/.env.local"
echo "  WP admin: $WP_URL/wp-admin (admin / admin)"
